const hexToRgba = (hex, alpha) => {
    const r = parseInt(hex.slice(1, 3), 16)
    const g = parseInt(hex.slice(3, 5), 16)
    const b = parseInt(hex.slice(5, 7), 16)
    return `rgba(${r}, ${g}, ${b}, ${alpha})`
}

// Stessa tinta di hexToRgba(hex, alpha) ma pre-miscelata su una base
// opaca invece di usare la trasparenza reale — le card sopra la foto di
// sfondo fissa della pagina non devono lasciarla trasparire (segnalato
// dall'utente), quindi qui il "peso" della tinta è nel colore risultante,
// non nell'alpha (che resta sempre 1).
const mixHexOverRgb = (hex, alpha, baseRgb) => {
    const r = parseInt(hex.slice(1, 3), 16)
    const g = parseInt(hex.slice(3, 5), 16)
    const b = parseInt(hex.slice(5, 7), 16)
    const [br, bg, bb] = baseRgb
    const mix = (channel, base) => Math.round(channel * alpha + base * (1 - alpha))
    return `rgb(${mix(r, br)}, ${mix(g, bg)}, ${mix(b, bb)})`
}

const mkThemeToPalette = (mkTheme, dark = false) => {
    const { colors } = mkTheme
    const primary = colors.primary
    const secondary = colors.secondary

    if (dark) {
        const darkBg = colors.bgDark
            ? `linear-gradient(180deg, ${colors.bgDark} 0%, #020617 100%)`
            : DARK_OVERRIDES.pageBackground
        return {
            accent: primary,
            accentSoft: hexToRgba(primary, 0.18),
            accentStrong: secondary,
            accentGlow: hexToRgba(primary, 0.32),
            pageBackground: darkBg,
            pageOverlay: DARK_OVERRIDES.pageOverlay,
            cardBackground: `linear-gradient(135deg, ${mixHexOverRgb(primary, 0.10, [30, 41, 59])}, rgb(15, 23, 42))`,
            navbarBackground: hexToRgba(primary, 0.2),
            border: hexToRgba(primary, 0.2),
            textSoft: '#94a3b8',
            textStrong: '#f8fafc',
        }
    }

    const lightBg = colors.bgLight
        ? `linear-gradient(180deg, ${colors.bgLight} 0%, #f8fafc 100%)`
        : `linear-gradient(180deg, ${hexToRgba(primary, 0.06)} 0%, #f8fafc 100%)`

    return {
        accent: primary,
        accentSoft: hexToRgba(primary, 0.18),
        accentStrong: secondary,
        accentGlow: hexToRgba(primary, 0.32),
        pageBackground: lightBg,
        pageOverlay: `radial-gradient(circle at top right, ${hexToRgba(primary, 0.12)}, transparent 42%), radial-gradient(circle at bottom left, ${hexToRgba(secondary, 0.1)}, transparent 34%)`,
        cardBackground: `linear-gradient(135deg, rgb(255, 255, 255), ${mixHexOverRgb(primary, 0.06, [255, 255, 255])})`,
        navbarBackground: 'rgba(15, 23, 42, 0.9)',
        border: hexToRgba(primary, 0.2),
        textSoft: '#475569',
        textStrong: '#0f172a',
    }
}

const toTheme = (palette, characterName, player, dark = false, mkTheme = null) => {
    const base = {
        ...palette,
        characterName,
        teamName: characterName ? `${characterName} Team` : 'Lega Kart Team',
        playerNickname: player?.nickname ?? null,
        avatarUrl: player?.img_url ?? null,
        hasPlayerAvatar: Boolean(player?.img_url),
        isPersonalized: Boolean(characterName),
        tailwind: mkTheme?.tailwind ?? palette.tailwind ?? DEFAULT_THEME.tailwind,
        animationClass: mkTheme?.animationClass ?? null,
        assets: mkTheme?.assets ?? null,
        characterType: mkTheme?.type ?? null,
        characterDescription: mkTheme?.description ?? null,
    }
    if (dark) {
        return {
            ...base,
            ...DARK_OVERRIDES,
            accent: palette.accent,
            accentSoft: palette.accentSoft,
            accentStrong: palette.accentStrong,
            accentGlow: palette.accentGlow,
            tailwind: {
                ...base.tailwind,
                textStrong: 'text-[#f8fafc]',
            },
        }
    }
    return base
}

export const getProfileTheme = (user, charactersById, dark = false) => {
    const player = user?.player ?? null
    const character = player?.favorite_character_id ? charactersById?.get(player.favorite_character_id) ?? null : null
    const normalizedCharacterName = normalizeText(character?.name)

    if (normalizedCharacterName) {
        const mkTheme = MARIO_KART_THEMES[normalizedCharacterName]
        if (mkTheme) {
            const palette = mkThemeToPalette(mkTheme, dark)
            return toTheme(palette, mkTheme.name, player, dark, mkTheme)
        }
    }

    if (!character) {
        return toTheme(DEFAULT_THEME, null, player, dark)
    }

    const palette = PALETTES[hashString(normalizedCharacterName) % PALETTES.length]
    return toTheme(palette, character.name, player, dark)
}
